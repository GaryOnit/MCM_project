def verify(path):
    """重新用 python-docx 打开，校验结构与字数。"""
    from docx import Document
    doc = Document(path)
    paras = doc.paragraphs
    heads = [(p.style.name, p.text) for p in paras
             if p.style.name.startswith('Heading') and p.text.strip()]
    text = '\n'.join(p.text for p in paras)
    for t in doc.tables:
        for row in t.rows:
            for cell in row.cells:
                text += '\n' + cell.text
    body_chars = len(re.sub(r'\s', '', text))
    n_ph = len(re.findall(r'【待补', text))
    imgs = len(doc.inline_shapes)
    print('段落数：%d，表格数：%d，内嵌图：%d' % (len(paras), len(doc.tables), imgs))
    print('去空白字符数：%d，【待补】标记数：%d' % (body_chars, n_ph))
    print('标题层级检查：')
    for lvl, txt in heads:
        print('   ', lvl, '|', txt)
    return heads


if __name__ == '__main__':
    out = build()
    print('已生成：', out, os.path.getsize(out) // 1024, 'KB')
    verify(out)
