def references(B, cites):
    B.h1('参考文献')
    for i, key in enumerate(cites.order, start=1):
        B.reference('[%d]　%s' % (i, REFS[key]))
    missing = [k for k in REFS if k not in cites.order]
    if missing:
        raise RuntimeError('以下文献未被正文引用：%s' % missing)




