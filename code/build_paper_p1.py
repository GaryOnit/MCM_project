class Cites:
    """把正文中的 {{key}} 标记按首次出现顺序替换为 [n]。"""

    PATTERN = re.compile(r'\{\{([^}]+)\}\}')

    def __init__(self, refs):
        self.refs = refs
        self.order = []

    def _num(self, key):
        key = key.strip()
        if key not in self.refs:
            raise KeyError('未定义的参考文献键：%s' % key)
        if key not in self.order:
            self.order.append(key)
        return self.order.index(key) + 1

    def resolve(self, text):
        if not text:
            return text

        def repl(m):
            keys = [k for k in m.group(1).split(',') if k.strip()]
            nums = [self._num(k) for k in keys]
            # GB/T 7714：连续编号用短横线连接（[1-2]、[5-7]），离散编号用逗号
            if len(nums) >= 2 and nums == list(range(nums[0], nums[0] + len(nums))):
                body = '%d-%d' % (nums[0], nums[-1])
            else:
                body = ','.join(str(n) for n in nums)
            return '[' + body + ']'

        return self.PATTERN.sub(repl, text)


class PaperC(Paper):
    """在 Paper 之上加一层引用标记解析与中西文间距规范化。"""

    _GAP_L = re.compile(r'(?<=[\u4e00-\u9fff])(?=\d)')
    _GAP_R = re.compile(r'(?<=\d)(?=[\u4e00-\u9fff])')
    _GAP_L2 = re.compile(r'(?<=[\u4e00-\u9fff])(?=[A-Za-z])')
    _GAP_R2 = re.compile(r'(?<=[A-Za-z])(?=[\u4e00-\u9fff])')
    _THOU = re.compile(r'(?<![\d.,A-Za-z])(\d{5,})(?![\d])')

    def __init__(self, cites):
        super().__init__()
        self.cites = cites

    @classmethod
    def norm(cls, text):
        """中西文间距规范化（中文与数字、拉丁字母之间补半角空格）；
        并对 5 位及以上的整数加千位分隔符（年份为 4 位，不受影响）。"""
        if not text:
            return text
        text = cls._GAP_R.sub(' ', cls._GAP_L.sub(' ', text))
        text = cls._GAP_R2.sub(' ', cls._GAP_L2.sub(' ', text))
        return cls._THOU.sub(lambda m: '{:,}'.format(int(m.group(1))), text)

    def p(self, text='', raw=False, **kw):
        if raw:      # 原样输出（保留文件名等字面量，不补间距、不加千分位）
            return super().p(self.cites.resolve(text), **kw)
        return super().p(self.norm(self.cites.resolve(text)), **kw)

    def h2(self, text):
        return super().h2(self.norm(self.cites.resolve(text)))

    def h3(self, text):
        return super().h3(self.norm(self.cites.resolve(text)))

    def table(self, caption, header, rows, raw=False, **kw):
        if raw:      # 原样输出（附录样例表：数字不加千分位、不改间距）
            header = [self.cites.resolve(h) for h in header]
            rows = [[self.cites.resolve(c) for c in r] for r in rows]
            cap = self.cites.resolve(caption)
        else:
            header = [self.norm(self.cites.resolve(h)) for h in header]
            rows = [[self.norm(self.cites.resolve(c)) for c in r] for r in rows]
            cap = self.norm(self.cites.resolve(caption))
        return super().table(cap, header, rows, **kw)

    def figure(self, path, caption=None, **kw):
        return super().figure(path, self.norm(self.cites.resolve(caption)), **kw)

    _URL_RE = re.compile(r'https?://\S+')

    def reference(self, text, **kw):
        # URL 原样输出（避免千分位/间距改写破坏链接），其余片段照常规范化
        parts, last = [], 0
        for m in self._URL_RE.finditer(text):
            parts.append(self.norm(text[last:m.start()]))
            parts.append(m.group(0))
            last = m.end()
        parts.append(self.norm(text[last:]))
        return super().reference(''.join(parts), **kw)

    def bullet(self, text, **kw):
        """编号条目：（1）……，首行缩进 2 字符。"""
        return self.p(text, **kw)


